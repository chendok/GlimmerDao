def get_yinyun_wuxing(char: str) -> str:
    """获取汉字的音韵五行（按拼音声母，五音十二律规则）。"""
    if not char:
        return "土"
    initial = _PINYIN_INITIAL.get(char, "")
    if not initial:
        return "土"  # 未收录拼音，音韵五行兜底为土（喉音/零声母）
    return _INITIAL_WUXING.get(initial, "土")


# ── 五格数理计算 ──────────────────────────────────────────────────
def analyze_name(name: str) -> dict:
    """对姓名做五格数理与五行分析。

    返回结构化字典，供报告「姓名分析」章节直接引用。
    单字/双字名均支持；复姓（二字姓）与单姓（一字姓）均支持。
    """
    name = (name or "").strip()
    if not name:
        return {"valid": False, "reason": "姓名为空"}

    chars = list(name)
    # 只保留汉字（去除非汉字字符如空格、·、姓与名分隔符）
    hanzi = [c for c in chars if "\u4e00" <= c <= "\u9fff"]
    if not hanzi:
        return {"valid": False, "reason": "未识别到有效汉字"}

    # 判断单姓/复姓：常见复姓集合
    fu_xing_set = {
        "欧阳", "司马", "上官", "诸葛", "东方", "独孤", "南宫", "夏侯",
        "皇甫", "尉迟", "公孙", "慕容", "长孙", "宇文", "司徒", "司空",
        "申屠", "令狐", "轩辕", "百里", "呼延", "东郭", "西门", "南宫",
        "端木", "钟离", "拓跋", "夹谷", "太史", "公冶", "宗政", "濮阳",
        "淳于", "单于", "闻人", "闾丘", "第五", "羊舌", "微生", "梁丘",
        "左丘", "东门", "西门", "壤驷", "公良", "漆雕", "乐正", "宰父",
        "谷梁", "段干", "百里", "南门", "公仪", "公输", "万俟", "司寇",
    }
    first_two = "".join(hanzi[:2])
    if first_two in fu_xing_set:
        xing = hanzi[:2]
        ming = hanzi[2:]
    else:
        xing = hanzi[:1]
        ming = hanzi[1:]

    if not ming:
        return {"valid": False, "reason": "未识别到名字"}

    xing_strokes = [get_stroke(c) for c in xing]
    ming_strokes = [get_stroke(c) for c in ming]
    total_strokes = sum(xing_strokes) + sum(ming_strokes)

    # 天格
    if len(xing) == 1:
        tian_ge = xing_strokes[0] + 1
    else:
        tian_ge = sum(xing_strokes)

    # 人格
    if len(xing) == 1:
        ren_ge = xing_strokes[0] + ming_strokes[0]
    else:
        ren_ge = xing_strokes[-1] + ming_strokes[0]

    # 地格
    if len(ming) == 1:
        di_ge = ming_strokes[0] + 1
    else:
        di_ge = sum(ming_strokes)

    # 总格
    zong_ge = total_strokes

    # 外格
    wai_ge = zong_ge - ren_ge + 1

    def _wuxing_shu(num: int) -> str:
        return _number_wuxing(num)

    # 三才配置：天格数理五行、人格数理五行、地格数理五行
    san_cai = {
        "tian": _wuxing_shu(tian_ge),
        "ren": _wuxing_shu(ren_ge),
        "di": _wuxing_shu(di_ge),
    }

    # 三才相生关系
    def _sheng(a: str, b: str) -> str:
        sheng_map = {"木": "火", "火": "土", "土": "金", "金": "水", "水": "木"}
        return "相生" if sheng_map.get(a) == b else ("比和" if a == b else "相克")

    san_cai_relation = (
        f"天{_sheng(san_cai['tian'], san_cai['ren'])}"
        f"→人{_sheng(san_cai['ren'], san_cai['di'])}"
    )

    # 五格吉凶
    def _ge_info(num: int) -> dict:
        ji, meaning = _shu_li_ji_xiong(num)
        return {"数理": num, "五行": _wuxing_shu(num), "吉凶": ji, "含义": meaning}

    wu_ge = {
        "天格": _ge_info(tian_ge),
        "人格": _ge_info(ren_ge),
        "地格": _ge_info(di_ge),
        "外格": _ge_info(wai_ge),
        "总格": _ge_info(zong_ge),
    }

    # 各字五行（偏旁五行 / 字义五行 / 音韵五行 / 综合五行）
    char_wuxing = []
    for i, c in enumerate(hanzi):
        zi_yi = get_wuxing(c)
        char_wuxing.append({
            "字": c,
            "康熙笔画": get_stroke(c),
            "偏旁五行": get_pianpang_wuxing(c),
            "字义五行": zi_yi,
            "音韵五行": get_yinyun_wuxing(c),
            "综合五行": zi_yi,  # 姓名学综合五行以字义五行为主
        })

    return {
        "valid": True,
        "姓名": name,
        "姓氏": "".join(xing),
        "名字": "".join(ming),
        "单复姓": "复姓" if len(xing) == 2 else "单姓",
        "单双名": "单名" if len(ming) == 1 else "双名",
        "逐字": char_wuxing,
        "天格": tian_ge,
        "人格": ren_ge,
        "地格": di_ge,
        "外格": wai_ge,
        "总格": zong_ge,
        "五格": wu_ge,
        "三才": san_cai,
        "三才关系": san_cai_relation,
    }


def format_name_analysis(name: str) -> str:
    """将姓名学分析结果格式化为报告可引用的确定性文本。"""
    r = analyze_name(name)
    if not r.get("valid"):
        return ""

    lines: list[str] = []
    lines.append(f"姓名：{r['姓名']}（{r['单复姓']}、{r['单双名']}）")

    # 逐字康熙笔画 + 四列五行（偏旁/字义/音韵/综合）
    zi = "；".join(
        f"{c['字']}={c['康熙笔画']}画，偏旁五行{c['偏旁五行']}、字义五行{c['字义五行']}、"
        f"音韵五行{c['音韵五行']}、综合五行{c['综合五行']}"
        for c in r["逐字"]
    )
    lines.append(f"逐字康熙笔画与五行（偏旁/字义/音韵/综合）：{zi}")

    # 五格
    ge_lines = []
    for ge_name, info in r["五格"].items():
        ge_lines.append(
            f"{ge_name}{info['数理']}（{info['五行']}，{info['吉凶']}：{info['含义']}）"
        )
    lines.append("五格数理：" + "；".join(ge_lines))

    # 三才
    lines.append(
        f"三才配置：天格{r['三才']['tian']}·人格{r['三才']['ren']}·地格{r['三才']['di']}"
        f"（{r['三才关系']}）"
    )

    return "\n".join(lines)
