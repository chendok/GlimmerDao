async def load_system_prompt() -> str:
    """从 DB 加载当前生效的对话框系统提示词（fallback 到 SYSTEM_PROMPT 常量）

    供 Agent Harness 在每次对话前调用，确保管理员修改提示词后立即生效。
    """
    try:
        from ...database import async_session
        from ...services.system_config_service import load_active_prompt_content
        async with async_session() as db:
            content = await load_active_prompt_content(db, "chat_system")
            if content:
                return content
    except Exception as e:
        logger.warning("[prompts] 加载对话框系统提示词失败，使用默认值: %s", e)
    return SYSTEM_PROMPT


